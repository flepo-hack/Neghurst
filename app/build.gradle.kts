android {
  namespace = "com.example"
  // Plain 36, deliberately NOT `release(36) { minorApiLevel = 1 }`.
  //
  // A minor SDK version requires the matching platform to be installed. The CI
  // workflow installs `platforms;android-36`, not `android-36.1`, so asking for
  // minor level 1 gave the Kotlin compiler a partial stub classpath and every
  // core class outside the stub became unresolvable: android.util.DisplayMetrics,
  // android.view.Display and android.util.Point all failed to resolve, and
  // `compileDebugKotlin` died in app/src/main. Nothing in this app uses a 36.1
  // API, so the minor version bought nothing and cost the whole compile.
  compileSdk = 36
  ndkVersion = "27.2.12479018"

  defaultConfig {
    applicationId = "com.aistudio.rendera.dodge"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

    // Real NDK/CMake build of the native vision engine (app/src/main/cpp/CMakeLists.txt).
    externalNativeBuild {
      cmake {
        cppFlags += listOf("-std=c++17", "-O3", "-fno-finite-math-only", "-ffp-contract=fast")
        arguments += listOf("-DANDROID_STL=c++_shared")
      }
    }

    // Ship real device ABIs only. x86 is dropped (no emulator value) which keeps the
    // native payload honest instead of shipping three dead copies.
    ndk {
      abiFilters += listOf("arm64-v8a", "armeabi-v7a", "x86_64")
    }
  }

  externalNativeBuild {
    cmake {
      path = file("src/main/cpp/CMakeLists.txt")
      version = "3.22.1"
    }
  }

  signingConfigs {
    create("release") {
      val storePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      // Only attach a signing config when a keystore actually exists, otherwise
      // `assembleRelease` fails at configuration time instead of at signing time.
      if (file(storePath).exists()) {
        storeFile = file(storePath)
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      signingConfig = signingConfigs.getByName("debugConfig")
    }
  }

  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }

  buildFeatures {
    compose = true
    buildConfig = true
  }

  packaging {
    jniLibs {
      useLegacyPackaging = false
    }
  }

  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

